"""Refresh the about-page song data and small, locally hosted cover images."""

from io import BytesIO
from pathlib import Path
import json
import re
import time
import urllib.error
import urllib.parse
import urllib.request

from PIL import Image, ImageOps
import yaml


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "_data" / "song_list.yml"
OUTPUT = ROOT / "_data" / "songs.yml"
COVERS = ROOT / "assets" / "img" / "music"
HEADERS = {"User-Agent": "IshmamPortfolioMusic/1.0 (https://ishmamt.github.io/)"}


def fetch(url):
    request = urllib.request.Request(url.replace("http://", "https://", 1), headers=HEADERS)
    for attempt in range(3):
        try:
            with urllib.request.urlopen(request, timeout=25) as response:
                return response.read()
        except urllib.error.HTTPError as error:
            if error.code != 503 or attempt == 2:
                raise
            time.sleep(3 * (attempt + 1))


def release_for(song):
    if song.get("release_group"):
        return song["release_group"], song.get("album")

    query = urllib.parse.quote(f'recording:"{song["title"]}" AND artist:"{song["artist"]}"')
    url = f"https://musicbrainz.org/ws/2/recording/?query={query}&fmt=json&limit=50"
    results = json.loads(fetch(url))
    time.sleep(1.1)
    groups = {}
    for recording in results.get("recordings", []):
        credit = "".join(part.get("name", "") for part in recording.get("artist-credit", []) if isinstance(part, dict))
        if credit.casefold() != song["artist"].casefold():
            continue
        if not recording["title"].casefold().startswith(song["title"].casefold()):
            continue
        for release in recording.get("releases", []):
            group = release.get("release-group", {})
            if group.get("primary-type") == "Album" and not group.get("secondary-types"):
                groups[group["id"]] = group["title"]

    if len(groups) != 1:
        choices = ", ".join(f"{name} ({group_id})" for group_id, name in list(groups.items())[:5])
        raise ValueError(
            f'{song["title"]} by {song["artist"]}: could not choose one album. '
            f"Add its MusicBrainz release_group to {SOURCE.name}. Candidates: {choices or 'none'}"
        )
    group_id, album = next(iter(groups.items()))
    return group_id, album


def cover_for(group_id):
    url = f"https://coverartarchive.org/release-group/{group_id}/"
    data = json.loads(fetch(url))
    front = next((image for image in data["images"] if image.get("front") and image.get("approved")), None)
    if front is None:
        raise ValueError(f"No approved front cover for release group {group_id}")
    thumbnails = front.get("thumbnails", {})
    return thumbnails.get("250") or thumbnails.get("small") or front["image"]


def slug(song):
    value = f'{song["title"]}-{song["artist"]}'.casefold()
    return re.sub(r"[^a-z0-9]+", "-", value).strip("-")


def small_webp(data):
    with Image.open(BytesIO(data)) as source:
        cover = ImageOps.fit(ImageOps.exif_transpose(source).convert("RGB"), (200, 200), Image.Resampling.LANCZOS)
        output = BytesIO()
        cover.save(output, format="WEBP", quality=80, method=6)
        return output.getvalue()


def main():
    songs = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    if not isinstance(songs, list):
        raise ValueError(f"{SOURCE.name} must contain a list of songs")

    generated = []
    images = {}
    for song in songs:
        if not song.get("title") or not song.get("artist"):
            raise ValueError("Each song needs a title and artist")
        if song.get("cover_url"):
            cover_url, album = song["cover_url"], song.get("album")
        else:
            group_id, album = release_for(song)
            cover_url = cover_for(group_id)
        filename = f"{slug(song)}.webp"
        if filename in images:
            raise ValueError(f"Duplicate song: {song['title']} by {song['artist']}")
        images[filename] = small_webp(fetch(cover_url))
        generated.append({
            "title": song["title"],
            "artist": song["artist"],
            "album": album,
            "cover": f"/assets/img/music/{filename}",
        })
        print(f'{song["title"]} - {song["artist"]}: {album or "cover found"}')

    COVERS.mkdir(parents=True, exist_ok=True)
    for filename, data in images.items():
        path = COVERS / filename
        if not path.exists() or path.read_bytes() != data:
            path.write_bytes(data)
    output = "# Generated by scripts/update_songs.py. Edit _data/song_list.yml instead.\n"
    output += yaml.safe_dump(generated, allow_unicode=True, sort_keys=False, width=100)
    if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != output:
        OUTPUT.write_text(output, encoding="utf-8")


if __name__ == "__main__":
    main()
